'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8').replace(/^\uFEFF/, '');
const context = vm.createContext({ window: {} });
const code = {};
for (const file of ['poems.js', 'lexicon.js', 'analyzer.js']) {
  code[file] = read('preview/' + file);
  vm.runInContext(code[file], context);
}
const { POETRY_POEMS: poems, POETRY_EMOTIONS: emotions, PoetryAnalyzer: engine } = context.window;
const definition = JSON.parse(read('data/literary-validation.json'));
const inputs = definition.cases.map(item => {
  const poem = poems.find(p => p.id === item.poemId);
  assert.ok(poem, item.poemId);
  return { id: poem.id, title: poem.title, text: poem.text, source: poem.source, sourceUrl: poem.sourceUrl };
});
const fingerprint = crypto.createHash('sha256').update(JSON.stringify({
  inputs, lexicon: code['lexicon.js'], analyzer: code['analyzer.js']
})).digest('hex');
const dir = 'docs/validation-snapshots/' + definition.createdAt + '-' + fingerprint.slice(0, 12);
const snapshot = { createdAt: definition.createdAt, fingerprint,
  lexiconVersion: context.window.POETRY_LEXICON_VERSION, emotions,
  cases: inputs.map(poem => ({ ...poem, result: engine.analyze(poem.text) })) };
fs.mkdirSync(path.join(root, dir), { recursive: true });
for (const name of ['lexicon.js', 'analyzer.js']) {
  const file = path.join(root, dir, name);
  if (fs.existsSync(file)) assert.equal(fs.readFileSync(file, 'utf8'), code[name]);
  else fs.writeFileSync(file, code[name]);
}
const snapshotFile = dir + '/snapshot.json';
const serialized = JSON.stringify(snapshot, null, 2) + '\n';
if (fs.existsSync(path.join(root, snapshotFile))) assert.equal(read(snapshotFile), serialized);
else fs.writeFileSync(path.join(root, snapshotFile), serialized);
if (process.argv.includes('--capture-baseline')) {
  fs.writeFileSync(path.join(root, 'data/literary-validation-baseline.json'),
    JSON.stringify({ snapshotFile, fingerprint }, null, 2) + '\n');
  console.log('Captured baseline: ' + snapshotFile);
  process.exit(0);
}
const pointer = JSON.parse(read('data/literary-validation-baseline.json'));
const before = JSON.parse(read(pointer.snapshotFile));
const compiled = { createdAt: definition.createdAt, intro: definition.intro,
  beforeVersion: before.lexiconVersion, currentVersion: snapshot.lexiconVersion,
  baselineSnapshot: pointer.snapshotFile, currentSnapshot: snapshotFile, cases: [] };
for (const item of definition.cases) {
  const previous = before.cases.find(p => p.id === item.poemId);
  const current = snapshot.cases.find(p => p.id === item.poemId);
  assert.equal(previous.text, current.text, 'Comparison input changed: ' + item.poemId);
  const poem = poems.find(p => p.id === item.poemId);
  compiled.cases.push({ ...item, titleOfPoem: poem.title, poet: poem.poet,
    source: poem.source, sourceUrl: poem.sourceUrl, interpretationEmotionKeys: poem.interpretationEmotionKeys,
    interpretationReferences: poem.interpretationReferences || [],
    beforeResult: previous.result, currentResult: current.result,
    evidence: item.focusLines.map(no => {
      const line = current.result.lines[no - 1];
      assert.ok(line, item.id + ' line ' + no);
      return { no, text: line.text, beforeHits: previous.result.lines[no - 1].hits, currentHits: line.hits };
    }) });
}
fs.writeFileSync(path.join(root, 'preview/validation.js'),
  '// Generated by tools/build_literary_validation.cjs.\nwindow.POETRY_VALIDATION = ' + JSON.stringify(compiled, null, 2) + ';\n');
const names = vector => emotions.map((e, i) => e.name + ' ' + (vector[i] * 100).toFixed(1) + '%').join(' / ');
const report = ['작품 해석과 문학적 검증 사례 — 검토용 초안', '작성일: ' + definition.createdAt,
  'ChatGPT(Codex)의 작성 지원으로 구성했다. 계산은 현재 앱 코드로 실행했으며, 학생의 직접 검토가 완료되었다는 뜻은 아니다.',
  '해석은 수치를 맞추기 위한 정답표가 아니다. 본문에 근거한 하나의 읽기이며 참고 자료를 사용한 경우 별도로 적었다.',
  '1. 작품별 해석'];
for (const poem of poems) {
  report.push(poem.title + ' — ' + poem.poet, '주제: ' + poem.theme,
    '해석에서 읽은 정서: ' + poem.interpretationEmotionKeys.map(k => emotions.find(e => e.key === k).name).join(' · '),
    poem.interp, '본문 출처: ' + poem.sourceUrl);
  for (const ref of poem.interpretationReferences || []) report.push('해석 참고: ' + ref.title + ' ' + ref.url);
}
report.push('2. 문학적 검증 사례 3건', compiled.intro);
for (const item of compiled.cases) {
  report.push(item.titleOfPoem + ' — ' + item.title,
    '보완 전 [' + compiled.beforeVersion + ']: 감지 ' + item.beforeResult.totalHits + '회 / ' + names(item.beforeResult.vec),
    '현재 [' + compiled.currentVersion + ']: 감지 ' + item.currentResult.totalHits + '회 / ' + names(item.currentResult.vec));
  for (const line of item.evidence) report.push(line.no + '행: ' + line.text,
    '보완 전 근거: ' + (line.beforeHits.map(h => h.word + '→' + emotions[h.emotion].name).join(', ') || '없음'),
    '현재 근거: ' + (line.currentHits.map(h => h.word + '→' + emotions[h.emotion].name).join(', ') || '없음'));
  report.push('문학적 해석: ' + item.reading, '차이의 원인: ' + item.cause,
    '개선 방법: ' + item.improvement, '적용 상태: ' + item.status,
    '남은 한계: ' + item.remaining, '본문 출처: ' + item.sourceUrl);
}
report.push('3. 재현 기록', '보완 전 스냅샷: ' + compiled.baselineSnapshot,
  '현재 스냅샷: ' + compiled.currentSnapshot,
  '각 스냅샷에 정확한 본문·출처·분석 결과·사전·분석 코드가 들어 있다.',
  '재생성: python tools/build_preview_data.py 다음에 node tools/build_literary_validation.cjs 를 실행한다.',
  '그러면 현재 사전으로 보고서와 앱 검증 자료를 다시 만든다. 보완 전 스냅샷은 덮어쓰지 않는다.');
fs.writeFileSync(path.join(root, 'docs/작품해석_문학적검증_초안.txt'), report.join('\n\n') + '\n');
console.log('Built 15 interpretations and ' + compiled.cases.length + ' reproducible literary validation cases.');
